import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import {
  renderEgressTable,
  renderItAdminNetworkGuide,
  renderProxySupportTable,
  requiredCliHosts,
} from "../dist/cli/it-admin-network.js";
import { nodeSupportsEnvProxy, PROXY_VARS } from "../dist/cli/proxy.js";
import { DEFAULT_BASE_URL } from "../dist/config.js";
import { REGISTRY_URL } from "../dist/housekeeping/update.js";

const LIST = JSON.parse(
  readFileSync(new URL("../docs/network-egress.json", import.meta.url), "utf8"),
);

const guides = [
  {
    locale: "en",
    file: new URL("../docs/it-admin-network.md", import.meta.url),
    title: "# IT administrator network and proxy guide",
    languageLink: "[日本語](it-admin-network.ja.md)",
    systemStore: "system certificate store",
    noGlobalWarnings: "Do not use `NODE_NO_WARNINGS`, which hides every warning.",
    yes: "Yes",
    no: "No",
  },
  {
    locale: "ja",
    file: new URL("../docs/it-admin-network.ja.md", import.meta.url),
    title: "# IT 管理者向けネットワーク・プロキシガイド",
    languageLink: "[English](it-admin-network.md)",
    systemStore: "オペレーティングシステムの証明書ストア",
    noGlobalWarnings: "すべての警告を隠す `NODE_NO_WARNINGS` は使用しないでください。",
    yes: "はい",
    no: "いいえ",
  },
];

const generatedComment =
  "<!-- Generated by scripts/render-it-admin-network.mjs from docs/network-egress.json and src/cli/it-admin-network.ts. Do not edit. -->";

test("IT administrator guides are current and bilingual", () => {
  for (const guide of guides) {
    const rendered = renderItAdminNetworkGuide(guide.locale, LIST);
    assert.deepEqual(readFileSync(guide.file), Buffer.from(rendered, "utf8"));
    assert.ok(rendered.startsWith(`${guide.title}\n`));
    assert.ok(rendered.includes(generatedComment));
    assert.ok(rendered.includes(guide.languageLink));
    assert.ok(rendered.endsWith("\n"));
    assert.equal(rendered.endsWith("\n\n"), false);
  }
});

test("the guides list every host in the JSON, with its purpose in that language", () => {
  for (const { locale, file } of guides) {
    const guide = readFileSync(file, "utf8");
    for (const entry of LIST.hosts) {
      const table = renderEgressTable(locale, LIST, entry.component);
      const row = table
        .split("\n")
        .find((line) => line.startsWith(`| \`${entry.host}\` | ${entry.purpose[locale]}`));
      assert.ok(row, `${locale}: ${entry.host} under ${entry.component}`);
      if (entry.disable)
        assert.ok(row.includes(entry.disable[locale]), `${locale}: ${entry.host} disable`);
      if (entry.source)
        assert.ok(row.includes(`(${entry.source})`), `${locale}: ${entry.host} source`);
    }
    for (const component of LIST.components) {
      assert.ok(guide.includes(`### ${component.name[locale]}\n`), `${locale}: ${component.id}`);
    }
  }
});

test("the copy-paste list holds the CLI's required hosts", () => {
  const gatewayHost = new URL(DEFAULT_BASE_URL).hostname;
  const registryHost = new URL(REGISTRY_URL).hostname;
  const required = requiredCliHosts(LIST);
  assert.ok(required.includes(gatewayHost));
  // The update notice is optional, but the installers need the registry.
  assert.ok(required.includes(registryHost));
  for (const { locale, file } of guides) {
    const guide = readFileSync(file, "utf8");
    assert.ok(guide.includes(`\`\`\`text\n${required.join("\n")}\n\`\`\``), locale);
    for (const name of [
      "AIAND_BASE_URL",
      "AIAND_AUTH_URL",
      "AIAND_UPDATE_CHECK=0",
      "NO_UPDATE_CHECK=1",
      "CI",
      "http://127.0.0.1:<port>",
    ]) {
      assert.ok(guide.includes(name), `${locale} guide must name ${name}`);
    }
    assert.doesNotMatch(guide, /127\.0\.0\.1:\d+/);
  }
});

test("both guides suppress only the experimental proxy warning", () => {
  for (const { locale, file, noGlobalWarnings } of guides) {
    const guide = readFileSync(file, "utf8");
    assert.ok(
      guide.includes("--disable-warning=UNDICI-EHPA"),
      `${locale} guide must explain selective warning suppression`,
    );
    assert.ok(
      guide.includes(noGlobalWarnings),
      `${locale} guide must warn against hiding every warning`,
    );
  }
});

test("the proxy support table follows the CLI's proxy implementation", () => {
  for (const { locale, file, systemStore, yes, no } of guides) {
    const table = renderProxySupportTable(locale);
    for (const name of PROXY_VARS) {
      assert.ok(table.includes(name), `${locale} table must name ${name}`);
    }
    for (const version of ["v22.20.9", "v22.21.0"]) {
      const row = table.split("\n").find((line) => line.includes(`\`${version}\``));
      assert.ok(row, `${locale} table must include ${version}`);
      const expected = nodeSupportsEnvProxy(version) ? yes : no;
      assert.ok(row.includes(`| ${expected} |`), `${version} must report ${expected}`);
    }

    const guide = readFileSync(file, "utf8");
    for (const name of [
      "NO_PROXY",
      "NODE_USE_ENV_PROXY",
      "--use-system-ca",
      systemStore,
      "NODE_EXTRA_CA_CERTS",
      "22.21",
    ]) {
      assert.ok(guide.includes(name), `${locale} guide must name ${name}`);
    }
  }
});
