const cell = (text: string): string => text.replaceAll("|", "\\|").replaceAll("\n", " ");

function hostRow(text: GuideCopy, locale: ItAdminNetworkLocale, entry: EgressHost): string {
  const purpose = entry.source
    ? `${entry.purpose[locale]} ([${text.source}](${entry.source}))`
    : entry.purpose[locale];
  const disable = entry.disable?.[locale] ?? text.notNeeded;
  const needed = entry.required ? text.required : text.optional;
  return `| \`${entry.host}\` | ${cell(purpose)} | ${needed} | ${cell(disable)} |`;
}

/** One component's table: the hosts it contacts, required first. */
export function renderEgressTable(
  locale: ItAdminNetworkLocale,
  list: EgressList,
  component: string,
): string {
  const text = copy[locale];
  const rows = list.hosts
    .filter((entry) => entry.component === component)
    .sort((a, b) => Number(b.required) - Number(a.required))
    .map((entry) => hostRow(text, locale, entry));
  return [
    `| ${text.hostHeading} | ${text.purposeHeading} | ${text.neededHeading} | ${text.disableHeading} |`,
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

const uniqueHosts = (entries: EgressHost[]): string[] =>
  [...new Set(entries.map((entry) => entry.host))].sort();

/** The required hosts of every component that is not an agent: the CLI's own minimum. */
export function requiredCliHosts(list: EgressList): string[] {
  const agents = new Set(list.components.filter((c) => c.agent).map((c) => c.id));
  return uniqueHosts(list.hosts.filter((entry) => entry.required && !agents.has(entry.component)));
}

function renderEgressSection(locale: ItAdminNetworkLocale, list: EgressList): string {
  const text = copy[locale];
  const sections = list.components.map((component) => {
    const version = component.version ? `${text.versionChecked} \`${component.version}\`\n\n` : "";
    const note = `${version}${component.note ? `${component.note[locale]}\n\n` : ""}`;
    const callback = component.id === "sign-in" ? `\n\n${text.callback}` : "";
    return `### ${component.name[locale]}\n\n${note}${renderEgressTable(locale, list, component.id)}${callback}`;
  });
  const block = (hosts: string[]) => `\`\`\`text\n${hosts.join("\n")}\n\`\`\``;
  return [
    `## ${text.egressHeading}\n\n${text.egressScope}\n\n${text.requiredListIntro}\n\n${block(requiredCliHosts(list))}`,
    ...sections,
    `### ${text.everyHostHeading}\n\n${text.everyHostIntro}\n\n${block(uniqueHosts(list.hosts))}`,
  ].join("\n\n");
}

export function renderProxySupportTable(locale: ItAdminNetworkLocale): string {
  const text = copy[locale];
  const proxyVariables = PROXY_VARS.map((name) => `\`${name}\``).join(", ");
  const versionRows = NODE_VERSIONS.map((version) => {
    const supported = nodeSupportsEnvProxy(version) ? text.yes : text.no;
    return `| \`${version}\` | ${supported} |`;
  });
  return [
    `| ${text.configurationHeading} | ${text.supportHeading} |`,
    "| --- | --- |",
    `| ${text.proxyVariables} | ${proxyVariables} |`,
    ...versionRows,
    `| ${text.safeRequirement} |  |`,
  ].join("\n");
}

export function renderItAdminNetworkGuide(locale: ItAdminNetworkLocale, list: EgressList): string {
  const text = copy[locale];
  return `${[
    `# ${text.title}\n${GENERATED_COMMENT}\n${text.languageLink}`,
    `## ${text.scopeHeading}\n\n${text.scope}`,
    renderEgressSection(locale, list),
    `## ${text.proxyHeading}\n\n${text.proxyBehavior}\n\n${renderProxySupportTable(locale)}\n\n${text.certificates}\n\n${text.explicitFlags}`,
    `## ${text.agentsHeading}\n\n${text.agents}`,
  ].join("\n\n")}\n`;
}
