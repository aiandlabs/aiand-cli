/** Text in both languages the guide ships in. */
type EgressText = Record<ItAdminNetworkLocale, string>;

/**
 * How a listed host is reached, which is what the drift test checks it by:
 * `code` is named in src/ or an installer, `redirect` is reached by following
 * `via` (a release download, or the browser during sign-in), `npm` is the
 * registry npm uses for an agent's npm install, and `agent` is contacted by
 * the agent itself, with a public `source` for the claim.
 */
type EgressContact = "code" | "redirect" | "npm" | "agent";

type EgressComponent = {
  id: string;
  name: EgressText;
  agent?: boolean;
  /** The release (or commit) aiand installs, which the agent's entries were checked at. */
  version?: string | null;
  note?: EgressText;
};

type EgressHost = {
  host: string;
  component: string;
  required: boolean;
  contact: EgressContact;
  via?: string;
  purpose: EgressText;
  disable?: EgressText;
  source?: string;
};

/** docs/network-egress.json: every host the CLI, its installers and each agent contact. */
